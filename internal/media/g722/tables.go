// Package g722 实现 ITU-T G.722（模式 1，64 kbit/s，7 kHz 宽频）的编解码算法。
//
// 结构（照 ITU-T G.722 标准，也是各实现通行的做法）：
//
//   - 正交镜像滤波器组（QMF，标准 Table 11 的 24 抽头）把 16 kHz 输入分成
//     0–4 kHz（低带）与 4–8 kHz（高带）两个 8 kHz 子带；
//   - 两个子带各走一个自适应量化器 + 二阶极点/六阶零点预测器的 ADPCM；
//   - 模式 1 的码字是 8 位：**高 2 位给高带、低 6 位给低带**（每 2 个 16 kHz
//     样本出 1 字节 → 20ms = 320 样本 = 160 字节 = 64 kbit/s）。
//
// 本包是纯算法：Encoder / Decoder 各自持有全部状态，**不是并发安全的**，
// 由调用方（media.g722Codec）按方向串行化。表值全部来自标准（ITU-T G.722
// 的 QMF 系数表与量化器/标度因子表），与各参考实现逐位一致。
//
// 正确性由 testdata/ 下的参考向量钉死（向量由 FFmpeg 的参考实现一次性生成）：
// 编码逐字节一致、解码逐样本一致。
package g722

// 一帧（20ms）的样本数与字节数：320 样本（16 kHz）× 2 字节/样本 = 640 字节
// PCM → 160 字节码流（64 kbit/s）。
const (
	// FrameSamples 20ms @16kHz 的 PCM 样本数。
	FrameSamples = 320
	// FrameBytes 20ms 的码流字节数。
	FrameBytes = 160
)

// QMF 系数（ITU-T G.722 Table 11）。两条相位各 12 个抽头：
//   - qmfEven 乘延迟线的偶数下标样本（p[0]、p[2]、…），累加成 xout[1]；
//   - qmfOdd  乘延迟线的奇数下标样本（p[1]、p[3]、…），累加成 xout[0]。
//
// 12 个系数值依次为 3, -11, 12, 32, -210, 951, 3876, -805, 362, -156, 53, -11，
